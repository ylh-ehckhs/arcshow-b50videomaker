import test from 'node:test';
import assert from 'node:assert/strict';
import {assignItemsToSlots} from '../shared/ocr-slot-assignment.mjs';

const slot = (x, y) => ({rect: {x, y, w: 200, h: 90}});
const line = (text, x, y, w = 175) => ({text, x, y, w, h: 14});

test('missed score lines cannot make consecutive cards share another card’s text', () => {
  const slots = [slot(400, 1200), slot(400, 1320), slot(400, 1440)];
  const lines = [
    line('JUTTZO', 400, 1230),
    line('Potentiat10.5>12.2056', 400, 1250),
    line('魔王', 400, 1325),
    line('037J7JJ7', 400, 1350),
    line('Potential11.1>12.1585', 400, 1370),
    line('junayingMacuia', 400, 1445),
    line('9905102', 400, 1470),
    line('Potentcial10.1>12.1259', 400, 1490),
  ];
  const assigned = assignItemsToSlots(lines, slots);
  assert.deepEqual(assigned.get(0), lines.slice(0, 2));
  assert.deepEqual(assigned.get(1), lines.slice(2, 5));
  assert.deepEqual(assigned.get(2), lines.slice(5));
  const all = [...assigned.values()].flat();
  assert.equal(all.length, lines.length);
  assert.equal(new Set(all).size, lines.length);
});

test('overlapping edge margins choose exactly one card in one column', () => {
  const slots = [slot(400, 100), slot(400, 205), slot(700, 100), slot(700, 205)];
  const first = line('first Potential', 395, 177);
  const second = line('second title', 395, 200);
  const other = line('right column score 9999999', 700, 135);
  const assigned = assignItemsToSlots([first, second, other], slots);
  assert.deepEqual(assigned.get(0), [first]);
  assert.deepEqual(assigned.get(1), [second]);
  assert.deepEqual(assigned.get(2), [other]);
  assert.deepEqual(assigned.get(3), []);
});

test('header, footer and cover noise cannot become card fields', () => {
  const assigned = assignItemsToSlots([
    line('BEST TOP50 AVG. 12.31624', 400, 30),
    line('Generated by Yurisaki', 400, 1000),
    line('cover', 200, 120, 80),
    line('Actual title', 390, 102),
  ], [slot(400, 100)]);
  assert.deepEqual(assigned.get(0).map(x => x.text), ['Actual title']);
});
