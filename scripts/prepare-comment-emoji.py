"""Prepare pinned local emoji artwork. Development only; never run by the app.

Existing glyphs retain the 3.0.0 artwork explicitly selected in the user's
comparison. Later Unicode sequences are supplemented from the same vendor.
"""
import hashlib
import io
import json
from pathlib import Path
import tarfile
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
CACHE = ROOT / '.cache/emoji-source'
DEST = ROOT / 'resources/emoji/apple'
SOURCES = [
    ('3.0.0', 'apple-research.tgz', '27fa37cbf0e40422536b4517a00165e296ea4abae2e6150bd977188480b4b0d3'),
    ('16.0.0', 'apple-supplement.tgz', 'b34d1665e136f163b0d4433318df151895b785186e8c729b2211b43017945075'),
]


def key(unified):
    return '-'.join(format(int(cp, 16), '04x') for cp in unified.split('-') if int(cp, 16) != 0xFE0F)


def variants(rows):
    for row in rows:
        yield row
        yield from row.get('skin_variations', {}).values()


def main():
    CACHE.mkdir(parents=True, exist_ok=True)
    DEST.mkdir(parents=True, exist_ok=True)
    (DEST / 'images').mkdir(exist_ok=True)
    assets = {}
    provenance = []
    for version, cached, expected in SOURCES:
        url = f'https://registry.npmjs.org/emoji-datasource-apple/-/emoji-datasource-apple-{version}.tgz'
        file = CACHE / cached
        if not file.exists():
            file.write_bytes(urllib.request.urlopen(url, timeout=60).read())
        data = file.read_bytes()
        assert hashlib.sha256(data).hexdigest() == expected, f'Source checksum mismatch: {version}'
        count = 0
        with tarfile.open(fileobj=io.BytesIO(data), mode='r:gz') as archive:
            rows = json.load(archive.extractfile('package/emoji.json'))
            members = {m.name: m for m in archive.getmembers() if m.isfile()}
            for row in variants(rows):
                name, unified = row.get('image', ''), row.get('unified', '')
                if not unified or not row.get('has_img_apple') or key(unified) in assets:
                    continue
                member = members.get('package/img/apple/64/' + name)
                if member is None:
                    continue
                # Only explicit PNG basenames from the pinned archive are copied.
                assert Path(name).name == name and name.endswith('.png')
                raw = archive.extractfile(member).read()
                assert raw[:8] == b'\x89PNG\r\n\x1a\n'
                (DEST / 'images' / name).write_bytes(raw)
                assets[key(unified)] = {'file': name, 'sha256': hashlib.sha256(raw).hexdigest(), 'version': version}
                count += 1
            for name in ('LICENSE', 'README.md'):
                if 'package/' + name in members:
                    (DEST / f'emoji-datasource-{version}-{name}').write_bytes(archive.extractfile('package/' + name).read())
        provenance.append({'package': 'emoji-datasource-apple', 'version': version, 'url': url, 'sha256': expected, 'glyphs': count})

    mapping = {k: v['file'] for k, v in sorted(assets.items())}
    module = '// Generated by scripts/prepare-comment-emoji.py; local files only.\n'
    module += 'export const COMMENT_EMOJI_FILES=Object.freeze(' + json.dumps(mapping, ensure_ascii=True, separators=(',', ':')) + ');\n'
    (ROOT / 'shared/comment-emoji-data.mjs').write_text(module, encoding='utf-8')
    manifest = {'style': 'User-selected Apple artwork', 'sources': provenance, 'glyphCount': len(mapping), 'assets': dict(sorted(assets.items()))}
    (DEST / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=True, indent=2) + '\n', encoding='utf-8')
    print(json.dumps({'glyphCount': len(mapping), 'sources': provenance, 'bytes': sum(p.stat().st_size for p in (DEST / 'images').iterdir())}))


if __name__ == '__main__':
    main()
